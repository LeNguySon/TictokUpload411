"""
Per-profile browser fingerprint: unique, coherent (Windows + Chrome) and FIXED for the profile's lifetime.

The schema is the SamMonny daemon's ``fingerprint`` record, so a fingerprint generated by the daemon (Bayesian
network) and one generated here are stored and applied the same way (profiles.fingerprint_json).
Local generation is seeded with the profile uuid: the same profile always gets the same fingerprint, even if
it has to be regenerated, while two profiles never share noise values.
"""

from __future__ import annotations

import hashlib
import json
import random
from typing import Any

DEFAULT_CHROME_MAJOR = 139

# (weight, vendor brand, renderer). Real ANGLE/D3D11 strings of common Windows desktop/laptop GPUs.
_GPUS: tuple[tuple[int, str, str], ...] = (
    (9, "NVIDIA", "NVIDIA GeForce RTX 3060 Direct3D11 vs_5_0 ps_5_0, D3D11"),
    (6, "NVIDIA", "NVIDIA GeForce GTX 1650 Direct3D11 vs_5_0 ps_5_0, D3D11"),
    (5, "NVIDIA", "NVIDIA GeForce RTX 4060 Direct3D11 vs_5_0 ps_5_0, D3D11"),
    (4, "NVIDIA", "NVIDIA GeForce GTX 1660 SUPER Direct3D11 vs_5_0 ps_5_0, D3D11"),
    (3, "NVIDIA", "NVIDIA GeForce RTX 3050 Laptop GPU Direct3D11 vs_5_0 ps_5_0, D3D11"),
    (8, "Intel", "Intel(R) UHD Graphics 630 Direct3D11 vs_5_0 ps_5_0, D3D11"),
    (7, "Intel", "Intel(R) Iris(R) Xe Graphics Direct3D11 vs_5_0 ps_5_0, D3D11"),
    (5, "Intel", "Intel(R) UHD Graphics 620 Direct3D11 vs_5_0 ps_5_0, D3D11"),
    (4, "AMD", "AMD Radeon RX 6600 Direct3D11 vs_5_0 ps_5_0, D3D11"),
    (3, "AMD", "AMD Radeon(TM) Graphics Direct3D11 vs_5_0 ps_5_0, D3D11"),
    (2, "AMD", "AMD Radeon RX 580 Series Direct3D11 vs_5_0 ps_5_0, D3D11"),
)
_SCREENS: tuple[tuple[int, int, int], ...] = (
    (34, 1920, 1080),
    (14, 1366, 768),
    (11, 1536, 864),
    (8, 2560, 1440),
    (7, 1440, 900),
    (6, 1600, 900),
    (5, 1280, 720),
    (4, 1920, 1200),
)
_CORES: tuple[tuple[int, int], ...] = ((20, 8), (18, 4), (16, 6), (14, 12), (8, 16), (4, 2))
_MEMORY: tuple[tuple[int, int], ...] = ((80, 8), (20, 4))  # navigator.deviceMemory is capped at 8


def _pick(rng: random.Random, table: tuple[tuple[Any, ...], ...]) -> tuple[Any, ...]:
    weights = [row[0] for row in table]
    return rng.choices(table, weights=weights, k=1)[0][1:]


def _rng(seed: str, salt: str) -> random.Random:
    digest = hashlib.sha256(f"{salt}:{seed}".encode()).digest()
    return random.Random(int.from_bytes(digest, "big"))


def user_agent(chrome_major: int = DEFAULT_CHROME_MAJOR) -> str:
    return (
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) "
        f"Chrome/{chrome_major}.0.0.0 Safari/537.36"
    )


def media_device_uid(seed: str) -> str:
    return hashlib.sha256(f"media:{seed}".encode()).hexdigest()[:36]


def generate_fingerprint(seed: str, chrome_major: int = DEFAULT_CHROME_MAJOR) -> dict[str, Any]:
    """Deterministic fingerprint for ``seed`` (the profile uuid), in the daemon's record schema."""
    rng = _rng(seed, "fingerprint.v1")
    brand, renderer = _pick(rng, _GPUS)
    width, height = _pick(rng, _SCREENS)
    (cores,) = _pick(rng, _CORES)
    (memory,) = _pick(rng, _MEMORY)
    return {
        "os": "win",
        "navigator": {
            "user_agent": user_agent(chrome_major),
            "platform": "Win32",
            "hardware_concurrency": cores,
            "device_memory": memory,
            "do_not_track": False,
        },
        "screen": {"width": width, "height": height, "color_depth": 24, "pixel_ratio": 1},
        "webgl": {"vendor": f"Google Inc. ({brand})", "renderer": f"ANGLE ({brand}, {renderer})"},
        "canvas_noise": round(rng.uniform(1.0, 10.0), 8),
        "audio_noise": float(f"{rng.uniform(1e-7, 9.9e-7):.10e}"),
        "webgl_noise": round(rng.uniform(80.0, 99.0), 6),
        "client_rects_noise": round(rng.uniform(1.0, 9.9), 8),
        "timezone": {"mode": "auto"},
    }


def fingerprint_of(profile: dict[str, Any]) -> dict[str, Any]:
    """The profile's stored fingerprint, or the deterministic one derived from its uuid."""
    raw = profile.get("fingerprint_json")
    if raw:
        try:
            fp = json.loads(raw) if isinstance(raw, str) else raw
            if isinstance(fp, dict) and fp.get("navigator"):
                return fp
        except (TypeError, ValueError):
            pass
    seed = str(profile.get("uuid") or profile.get("id") or profile.get("name") or "")
    return generate_fingerprint(seed)


def profile_columns(fp: dict[str, Any]) -> dict[str, Any]:
    """profiles columns mirroring ``fp`` (fingerprint_json is the source of truth)."""
    nav = fp.get("navigator") or {}
    screen = fp.get("screen") or {}
    webgl = fp.get("webgl") or {}
    cols: dict[str, Any] = {
        "fingerprint_json": json.dumps(fp, ensure_ascii=False, sort_keys=True),
        "user_agent": nav.get("user_agent"),
        "os_type": fp.get("os", "win"),
        "resolution": f"{screen.get('width')}x{screen.get('height')}" if screen else None,
        "cpu_cores": nav.get("hardware_concurrency"),
        "memory_gb": nav.get("device_memory"),
        "canvas_noise": fp.get("canvas_noise"),
        "audio_noise": fp.get("audio_noise"),
        "webgl_noise": fp.get("webgl_noise"),
        "webgl_vendor": webgl.get("vendor"),
        "webgl_renderer": webgl.get("renderer"),
    }
    tz = fp.get("timezone") or {}
    if tz.get("timezone_id"):
        cols["timezone_id"] = tz["timezone_id"]
    return {k: v for k, v in cols.items() if v is not None}


def gologin_preferences(fp: dict[str, Any], seed: str) -> dict[str, Any]:
    """Fingerprint part of Orbita's Default/Preferences "gologin" section (no shared constants)."""
    nav = fp.get("navigator") or {}
    screen = fp.get("screen") or {}
    webgl = fp.get("webgl") or {}
    vendor, renderer = webgl.get("vendor"), webgl.get("renderer")
    # Values missing from older daemon records are derived from the seed, never a shared default.
    local = generate_fingerprint(seed)
    canvas = float(fp.get("canvas_noise") or local["canvas_noise"])
    audio = float(fp.get("audio_noise") or local["audio_noise"])
    webgl_noise = float(fp.get("webgl_noise") or local["webgl_noise"])
    rects = float(fp.get("client_rects_noise") or local["client_rects_noise"])
    return {
        "userAgent": nav.get("user_agent") or local["navigator"]["user_agent"],
        "screenWidth": int(screen.get("width") or local["screen"]["width"]),
        "screenHeight": int(screen.get("height") or local["screen"]["height"]),
        "navigator": {"platform": nav.get("platform") or "Win32", "max_touch_points": 0},
        "hardwareConcurrency": int(nav.get("hardware_concurrency") or local["navigator"]["hardware_concurrency"]),
        "deviceMemory": int(nav.get("device_memory") or local["navigator"]["device_memory"]) * 1024,
        "doNotTrack": bool(nav.get("do_not_track", False)),
        "canvasMode": "noise",
        "canvasNoise": canvas,
        "audioContext": {"enable": True, "noiseValue": audio},
        "clientRects": {"mode": "noise", "noise": rects},
        "client_rects_noise_enable": True,
        "getClientRectsNoice": rects,
        "get_client_rects_noise": rects,
        "webgl": {"metadata": {"vendor": vendor or local["webgl"]["vendor"],
                               "renderer": renderer or local["webgl"]["renderer"], "mode": True}},
        "webGl": {"vendor": vendor or local["webgl"]["vendor"],
                  "renderer": renderer or local["webgl"]["renderer"], "mode": True},
        "webgl_noice_enable": True,
        "webglNoiceEnable": True,
        "webgl_noise_enable": True,
        "webgl_noise_value": webgl_noise,
        "webglNoiseValue": webgl_noise,
        "mediaDevices": {"enable": True, "uid": media_device_uid(seed), "audioInputs": 1, "audioOutputs": 1,
                         "videoInputs": 1},
    }
